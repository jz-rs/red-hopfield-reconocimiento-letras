# === Mostrar letra ===
def mostrar_letra(vec, titulo=""):
    plt.figure(figsize=(2, 2))
    plt.imshow(-vec.reshape(10, 10), cmap="gray", vmin=-1, vmax=1)  # <── cambiado a 10x10
    plt.axis("off")
    plt.title(titulo)
    plt.show()

# === Imagen a vector ===
def imagen_a_vector(ruta, size=(10, 10)):  # <── cambiado a 10x10
    img = Image.open(ruta).convert("L").resize(size)
    data = np.array(img)
    data = np.where(data < 128, 1, -1)
    return data.flatten()

# === Mostrar densidad de píxeles negros ===
